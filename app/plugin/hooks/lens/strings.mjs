/** "zh-TW, 正體中文"、"zh"、"中文" → zh；其他有設定的值 → en；沒設定 → en */
export function langOf(setting) {
  const s = String(setting ?? '').trim();
  return /^zh|中文/i.test(s) ? 'zh' : 'en';
}
